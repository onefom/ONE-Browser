import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const source=await readFile(new URL('../public/one-browser/app.js',import.meta.url),'utf8');
const helper=source.split('\n').find(line=>line.startsWith('async function renameEnvironment('));
assert(helper);
const calls=[];let releaseBoot;
const boot=new Promise(resolve=>releaseBoot=resolve);
const context={window:{oneBrowserDirectorySync:boot},desktopBridge:()=>({renameBrowserWindow:async input=>{calls.push(input);return {deferred:true}}}),Error,Boolean};
vm.createContext(context);vm.runInContext(helper,context);
const entry={windowId:'11111111-1111-4111-8111-111111111111',profileId:'existing-profile',name:'原名'};
context.entry=entry;
const pending=vm.runInContext("renameEnvironment(entry,'新名称')",context);
await Promise.resolve();assert.equal(calls.length,0,'rename must wait for initial directory migration');
releaseBoot();assert.equal(await pending,true);assert.equal(calls.length,1);
assert.equal(calls[0].id,entry.windowId);assert.equal(calls[0].profileId,entry.profileId);assert.equal(calls[0].name,'新名称');
assert.equal(entry.name,'原名','UI name commits only after the native call succeeds');
calls.length=0;assert.equal(await vm.runInContext("renameEnvironment(entry,'原名')",context),false);assert.equal(calls.length,0);
context.entry={windowId:'new',profileId:'',name:'尚未启动'};assert.equal(await vm.runInContext("renameEnvironment(entry,'新名称')",context),false);assert.equal(calls.length,0,'unstarted rows do not adopt another profile');
context.entry=entry;context.desktopBridge=()=>({renameBrowserWindow:async()=>{throw Error('rename failed')}});
await assert.rejects(vm.runInContext("renameEnvironment(entry,'失败名称')",context),/rename failed/);assert.equal(entry.name,'原名');
assert(source.includes("deferred?'窗口已改名，数据目录将在关闭后同步'"));
assert(source.includes('const editedEntry=environments[editingIndex]'),'async form submit must capture the original row');
console.log('One Browser directory rename, bootstrap ordering and failure preservation checks passed');
