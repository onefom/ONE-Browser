import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const context={};vm.runInNewContext(await readFile(new URL('../public/one-browser/account-links.js',import.meta.url),'utf8'),context);
const links=context.OneBrowserAccountLinks;let counter=0;const id=()=>`account-${++counter}`;
const accounts=[{service:'1'},{service:'2'},{service:'333',window:'old-window'}];
const windows=[{windowId:'window-a',name:'A',owner:'2'},{windowId:'window-b',name:'old-window',owner:'未关联账号'}];
links.normalize(accounts,windows,id,true);
assert.equal(windows[0].accountId,accounts[1].accountId);assert.equal(windows[1].accountId,accounts[2].accountId);
assert.equal(accounts[1].window,'A');assert.equal(accounts[2].window,'old-window');
const stable=accounts.map(account=>account.accountId);links.normalize(accounts,windows,id);assert.deepEqual(accounts.map(account=>account.accountId),stable);
links.assign(windows[1],accounts[1]);links.normalize(accounts,windows,id);
assert.equal(accounts[1].window,'A、old-window');assert.equal(accounts[2].window,'');
windows[1].name='renamed';windows.reverse();links.normalize(accounts,windows,id);
assert(accounts[1].window.includes('renamed'));assert.equal(windows[0].accountId,accounts[1].accountId);
links.assign(windows[0],null);links.normalize(accounts,windows,id);assert.equal(accounts[1].window,'A');assert.equal(windows[0].owner,'未关联账号');
accounts.splice(1,1);links.normalize(accounts,windows,id);assert.equal(windows[1].accountId,'');assert.equal(windows[1].owner,'未关联账号');
const duplicate=[{service:'same'},{service:'same'}],ambiguous=[{windowId:'x',name:'x',owner:'same'}];links.normalize(duplicate,ambiguous,id,true);
assert.notEqual(duplicate[0].accountId,duplicate[1].accountId);assert.equal(ambiguous[0].accountId,undefined);
links.assign(ambiguous[0],duplicate[1]);links.normalize(duplicate,ambiguous,id);assert.equal(duplicate[1].window,'x');assert.equal(duplicate[0].window,'');
console.log('Account/window stable identity, migration, bidirectional links, rename, reassignment and deletion checks passed');
