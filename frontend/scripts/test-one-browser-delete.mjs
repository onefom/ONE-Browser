import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const source=await readFile(new URL('../public/one-browser/app.js',import.meta.url),'utf8');
const helper=source.split('\n').find(line=>line.startsWith('async function deleteEnvironment('));
assert(helper);
let release,reply,calls=[];
const entry={windowId:'window-a',profileId:'profile-a',name:'A',state:'stopped'};
const other={windowId:'window-b',profileId:'profile-b',state:'stopped'};
const entries=[entry,other];
const context={window:{oneBrowserDirectorySync:new Promise(resolve=>release=resolve)},environments:entries,selectedEnvironmentIndexes:new Set([0]),currentFilter:'all',document:{querySelector:()=>({value:''})},render:()=>{},desktopBridge:()=>({deleteBrowserWindow:input=>{calls.push(input);return new Promise(resolve=>reply=resolve)}})};
vm.createContext(context);vm.runInContext(helper,context);context.entry=entry;
const pending=vm.runInContext('deleteEnvironment(entry)',context);
await Promise.resolve();assert.equal(calls.length,0);
release();await new Promise(resolve=>setImmediate(resolve));
assert.equal(calls[0].id,'window-a');assert.equal(calls[0].profileId,'profile-a');
assert(entries.includes(entry),'UI must retain record until backend acknowledges data removal');
entries.unshift({windowId:'new-window'});reply();await pending;
assert(!entries.includes(entry));assert(entries.includes(other));assert.equal(entries[0].windowId,'new-window');
assert.equal(context.selectedEnvironmentIndexes.size,0);
entries.push(entry);calls=[];
context.desktopBridge=()=>({deleteBrowserWindow:async()=>{throw Error('browser still running')}});
await assert.rejects(vm.runInContext('deleteEnvironment(entry)',context),/browser still running/);
assert(entries.includes(entry),'failure must retain the window');
context.desktopBridge=()=>({deleteBrowserWindow:async input=>calls.push(input)});
entry.state='running';await assert.rejects(vm.runInContext('deleteEnvironment(entry)',context),/运行/);
entry.state='stopped';entry.starting=true;await assert.rejects(vm.runInContext('deleteEnvironment(entry)',context),/启动/);
assert.equal(calls.length,0);
assert(source.includes("if(action==='delete')openDeleteWindow(entry)"));
console.log('One Browser deletion acknowledgement, stable identity, failure and running guards passed');
